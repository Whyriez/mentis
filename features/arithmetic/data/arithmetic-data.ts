export const initialMultiplicationFamilies: MultiplicationFamily[] = Array.from(
  { length: 10 },
  (_, idx) => {
    const num = idx + 1;
    let initialProgress = 100;
    let initialStatus: MultiplicationFamily["status"] = "Mastered";

    if (num === 7) {
      initialProgress = 70;
      initialStatus = "Practicing";
    } else if (num === 8) {
      initialProgress = 60;
      initialStatus = "Practicing";
    } else if (num === 9) {
      initialProgress = 80;
      initialStatus = "Practicing";
    }

    return {
      number: num,
      label: `${num}s Table (${num} × 1 to ${num} × 10)`,
      progressPercent: initialProgress,
      status: initialStatus,
      items: Array.from({ length: 10 }, (__, i) => ({
        a: num,
        b: i + 1,
        product: num * (i + 1),
        isMemorized: num <= 6 || num === 10,
      })),
    };
  }
);

